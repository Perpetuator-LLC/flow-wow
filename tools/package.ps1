<#
.SYNOPSIS
  Builds a release zip of the Flow addon: dist\Flow-<version>.zip, containing a
  single Flow\ folder ready to upload to CurseForge (or unzip into Interface\AddOns).

  Leaves out developer files (docs, tools, .git) and replaces the generated
  Learned\CombatLog.lua (your personal combat data) with an empty one.

.USAGE
  powershell -ExecutionPolicy Bypass -File tools\package.ps1
#>
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$toc = Get-Content (Join-Path $root 'Flow.toc') -Raw
$version = if ($toc -match '## Version:\s*(\S+)') { $Matches[1] } else { 'dev' }

$dist = Join-Path $root 'dist'
$stage = Join-Path $dist 'stage'
$out = Join-Path $stage 'Flow'
if (Test-Path $stage) { Remove-Item $stage -Recurse -Force }
New-Item -ItemType Directory -Force $out | Out-Null

foreach ($f in 'Flow.toc', 'Bindings.xml', 'Core.lua', 'README.md', 'CHANGELOG.md', 'LICENSE') {
    $src = Join-Path $root $f
    if (Test-Path $src) { Copy-Item $src $out }
}
foreach ($d in 'Modules', 'Classes') {
    Copy-Item (Join-Path $root $d) (Join-Path $out $d) -Recurse
}

# Clean learned-data placeholder (never ship someone's personal combat data).
New-Item -ItemType Directory -Force (Join-Path $out 'Learned') | Out-Null
$placeholder = @'
-- GENERATED by tools/analyze-combatlog.ps1. Empty until you run it on your
-- combat log files. Do not edit by hand: re-run the script instead.
local _, ns = ...
ns:Register("learned", "combatlog", {
    generated = nil,
    fights = 0,
    bias = { dps = {} },
    heals = {},
    mobs = {},
})
'@
[IO.File]::WriteAllText((Join-Path $out 'Learned\CombatLog.lua'), $placeholder, (New-Object Text.UTF8Encoding $false))

$zip = Join-Path $dist "Flow-$version.zip"
if (Test-Path $zip) { Remove-Item $zip -Force }
# Build the zip by hand: Windows PowerShell's Compress-Archive writes "\" in
# entry paths, which other platforms' unzip tools (and uploaders) mishandle.
Add-Type -AssemblyName System.IO.Compression, System.IO.Compression.FileSystem
$archive = [IO.Compression.ZipFile]::Open($zip, 'Create')
try {
    Get-ChildItem $out -Recurse -File | ForEach-Object {
        $rel = 'Flow/' + $_.FullName.Substring($out.Length + 1).Replace('\', '/')
        [IO.Compression.ZipFileExtensions]::CreateEntryFromFile($archive, $_.FullName, $rel) | Out-Null
    }
} finally { $archive.Dispose() }
Remove-Item $stage -Recurse -Force
Write-Host "Built $zip"
